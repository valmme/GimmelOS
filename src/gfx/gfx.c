uint32_t* framebuffer;
uint32_t width;
uint32_t height;
uint32_t pitch;

static uint32_t fb_cursor_x = 0;
static uint32_t fb_cursor_y = 0;

const uint32_t vga_palette[16] = {
    0x000000, 0x0000AA, 0x00AA00, 0x00AAAA,
    0xAA0000, 0xAA00AA, 0xAA5500, 0xAAAAAA,
    0x555555, 0x5555FF, 0x55FF55, 0x55FFFF,
    0xFF5555, 0xFF55FF, 0xFFFF55, 0xFFFFFF,
};

static uint32_t* backbuffer = 0;

gfx_color_t gfx_from_vga(vga_color_t c) {
    uint32_t rgb = vga_palette[c];
    return (gfx_color_t){
        .r = (rgb >> 16) & 0xFF,
        .g = (rgb >> 8)  & 0xFF,
        .b =  rgb        & 0xFF,
        .a =               0xFF
    };
}

void gfx_init(vec2 res, uint32_t p, uint32_t* fb) {
    width = res.x;
    height = res.y;

    pitch = p;
    framebuffer = fb;

    static uint32_t _backbuffer[1920 * 1080];
    backbuffer = _backbuffer;
}

void gfx_begin_frame(gfx_color_t color) {
    for (int i = 0; i < width * height; i++) {
        backbuffer[i] = ((uint32_t)color.r << 16) | ((uint32_t)color.g << 8) | (uint32_t)color.b;
    }
}

void gfx_end_frame(void) {
    uint8_t* dst = (uint8_t*)framebuffer;

    for (uint32_t y = 0; y < height; y++) {
        uint32_t* drow = (uint32_t*)(dst + y * pitch);
        uint32_t* srow = backbuffer + y * width;

        for (uint32_t x = 0; x < width; x++)
            drow[x] = srow[x];
    }
}

static uint8_t reverse_bits(uint8_t b) {
    b = (b & 0xF0) >> 4 | (b & 0x0F) << 4;
    b = (b & 0xCC) >> 2 | (b & 0x33) << 2;
    b = (b & 0xAA) >> 1 | (b & 0x55) << 1;
    return b;
}

void gfx_putchar_ex(char c, vec2 pos, gfx_color_t fg, gfx_color_t bg, int scale) {
    const uint8_t* glyph = font[(uint8_t)c];
    for (int row = 0; row < 8; row++) {
        uint8_t bits = reverse_bits(glyph[row]);

        for (int col = 0; col < 8; col++) {
            gfx_color_t color = (bits & (0x80 >> col)) ? fg : bg;
            for (int sy = 0; sy < scale; sy++) {
                for (int sx = 0; sx < scale; sx++) {
                    gfx_put_pixel(pos.x + col * scale + sx, pos.y + row * scale + sy, color);
                }
            }
        }
    }
}

void gfx_putchar(char c, vec2 pos, gfx_color_t fg, gfx_color_t bg) {
    gfx_putchar_ex(c, pos, fg, bg, 1);
}

void gfx_print_ex(const char* str, vec2 pos, gfx_color_t fg, gfx_color_t bg, int scale) {
    int start_x = pos.x;
    while (*str) {
        if (*str == '\n') {
            pos.y += FB_CHAR_H * scale;
            pos.x  = start_x;
        } 
        
        else {
            gfx_putchar_ex(*str, pos, fg, bg, scale);
            pos.x += FB_CHAR_W * scale;
        }
        str++;
    }
}

void gfx_print(const char* str, vec2 pos, gfx_color_t fg, gfx_color_t bg) {
    gfx_print_ex(str, pos, fg, bg, 1);
}

void gfx_put_pixel(uint32_t x, uint32_t y, gfx_color_t color) {
    if (x >= width || y >= height) return;
    uint32_t packed = ((uint32_t)color.r << 16) | ((uint32_t)color.g << 8) | (uint32_t)color.b;
    backbuffer[y * width + x] = packed;
}

void gfx_draw_line(vec2 a, vec2 b, gfx_color_t color) {
    int dx = (b.x > a.x) ? b.x - a.x : a.x - b.x;
    int sx = (a.x < b.x) ? 1 : -1;

    int dy = (b.y > a.y) ? b.y - a.y : a.y - b.y;
    int sy = (a.y < b.y) ? 1 : -1;

    int err = dx - dy;

    while (1) {
        gfx_put_pixel(a.x, a.y, color);

        if (a.x == b.x && a.y == b.y) break;

        int e2 = 2 * err;

        if (e2 > -dy) {
            err -= dy;
            a.x += sx;
        }

        if (e2 < dx) {
            err += dx;
            a.y += sy;
        }
    }
}

void gfx_draw_rec(rec r, gfx_color_t color) {
    // top, bottom, left, right
    for (int32_t x = r.x; x < r.x + (int32_t)r.w; x++) { gfx_put_pixel(x, r.y, color); }
    for (int32_t x = r.x; x < r.x + (int32_t)r.w; x++) { gfx_put_pixel(x, r.y + (int32_t)r.h - 1, color); }
    for (int32_t y = r.y; y < r.y + (int32_t)r.h; y++) { gfx_put_pixel(r.x, y, color); }
    for (int32_t y = r.y; y < r.y + (int32_t)r.h; y++) { gfx_put_pixel(r.x + (int32_t)r.w - 1, y, color); }
}

void gfx_draw_fill_rec(rec r, gfx_color_t color) {
    for (int32_t y = r.y; y < r.y + (int32_t)r.h; y++) {
        for (int32_t x = r.x; x < r.x + (int32_t)r.w; x++) {
            gfx_put_pixel(x, y, color);
        }
    }
}

static void cursor_save_bg(int32_t x, int32_t y) {
    for (int row = 0; row < CURSOR_H; row++) {
        for (int col = 0; col < CURSOR_W; col++) {
            int sx = x + col, sy = y + row;

            if (sx < 0 || sy < 0 || (uint32_t)sx >= width || (uint32_t)sy >= height)
                cursor_bg[row * CURSOR_W + col] = 0;

            else
                cursor_bg[row * CURSOR_W + col] = *((uint32_t*)((uint8_t*)framebuffer + sy * pitch + sx * 4));
        }
    }
}

static void cursor_restore_bg(int32_t x, int32_t y) {
    for (int row = 0; row < CURSOR_H; row++) {
        for (int col = 0; col < CURSOR_W; col++) {
            int sx = x + col, sy = y + row;
            if (sx < 0 || sy < 0 || (uint32_t)sx >= width || (uint32_t)sy >= height)
                continue;

            *((uint32_t*)((uint8_t*)framebuffer + sy * pitch + sx * 4)) = cursor_bg[row * CURSOR_W + col];
        }
    }
}

void gfx_draw_cursor(mouse_state_t mouse) {
    for (int row = 0; row < CURSOR_H; row++) {
        for (int col = 0; col < CURSOR_W; col++) {
            if (cursor_bitmap[row] & (1u << (31 - col)))
                gfx_put_pixel(mouse.pos.x + col, mouse.pos.y + row, GFX_WHITE);
        }
    }
}

void gfx_draw_texture(const uint32_t* tex, vec2 pos, vec2 size) {
    for (uint32_t row = 0; row < size.y; row++) {
        for (uint32_t col = 0; col < size.x; col++) {
            uint32_t packed = tex[row * size.x + col];

            uint8_t a = (packed >> 24) & 0xFF;
            if (a == 0) continue;

            gfx_color_t color = {
                .r = (packed >> 16) & 0xFF,
                .g = (packed >> 8)  & 0xFF,
                .b =  packed        & 0xFF,
                .a = a
            };

            gfx_put_pixel(pos.x + col, pos.y + row, color);
        }
    }
}

void gfx_render_frame() {
    mouse_init();
    wm_init();

    wm_create("Window 1", (rec){50,  50,  300, 200}, GFX_DARK_GRAY);
    wm_create("Window 2", (rec){200, 150, 250, 180}, GFX_DARK_GRAY);

    while (1) {
        mouse_poll();
        wm_handle_mouse(mouse.pos, mouse.left);

        gfx_begin_frame(GFX_DARK_BLUE);
        wm_draw_all();
        gfx_draw_cursor(mouse);
        gfx_end_frame();
    }
}

